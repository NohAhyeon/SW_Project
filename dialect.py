"""
부산·경상도 사투리 → 표준어 바꾸기 (대화 엔진이 의도를 판단하기 전에 사용)

  "약 뭐 묵노"        → "약 뭐 먹어"      → 약 질문
  "와 이리 어지럽노"  → "왜 이렇게 어지럽" → 몸 상태 확인
  "머라카노"          → "뭐라고"          → 다시 말해 주기
  "고마 됐다"         → "그만 됐다"       → 대화 끝
  "날 좀 살리도"      → "날 좀 살려줘"    → 위급

LLM 에는 어르신이 하신 말 그대로를 보내고(사투리를 더 잘 이해함),
규칙(약·일정·위급·다시 말해 주기)만 바꾼 표준어로 판단한다.
"""
import re

# (사투리 패턴, 표준어) — 위에서부터 차례로 바꾼다. 띄어쓰기가 없어도 되게 만든다.
RULES: list[tuple[str, str]] = [
    # 다시 말해 달라
    (r"머라\s*카노|뭐라\s*카노|머라\s*캤노|뭐라\s*캤노|머라\s*켔노|머라\s*하노|머라꼬|뭐라꼬|머라고", "뭐라고"),
    (r"안\s*들린다|안\s*들리노|안\s*들리네", "안 들려"),
    # 위급
    (r"살리\s*(도|주|도고|주라|주이소)", "살려줘"),
    (r"도와\s*(도|도고|주라|주이소|주소)", "도와줘"),
    (r"자빠졌|자빠짔|엎어졌|꼬꾸라졌|넘어짔|디비졌", "넘어졌"),
    (r"불\s*났다\s*카이|불\s*났데이", "불났다"),
    # 그만 ("고마워"는 그대로 둔다)
    (r"고마\s*(해라|하자|됐다|됐어|치아라|해)", r"그만 \1"),
    (r"^고마(?![워웠우운버])", "그만"),
    (r"치아라|치아뿌라", "그만해"),
    # 먹다
    (r"묵(?=[었엇어노나을고는다자제겠지으])", "먹"),
    (r"뭇(?=[나노다어])", "먹었"),
    (r"먹노|먹나(?=\?|$)", "먹어"),
    (r"무따|뭇따", "먹었다"),
    # 왜 / 뭐 / 어디 / 언제
    (r"(^|\s)와\s*이리", r"\1왜 이렇게"),
    (r"(^|\s)와\s+(?=\S+[노나고])", r"\1왜 "),
    (r"머꼬|뭐꼬|머고(?=\s|$|\?)", "뭐야"),
    (r"(^|\s)머(?=\s)", r"\1뭐"),
    (r"어데|어디고|어디노", "어디"),
    (r"언제고|언제노", "언제"),
    (r"몇\s*시고|몇\s*시노", "몇 시야"),
    (r"며칠이고|며칠이노", "며칠이야"),
    (r"무슨\s*요일이고|무슨\s*요일이노|무신\s*요일", "무슨 요일이야"),
    # 날씨
    (r"비\s*오나|비\s*오노|비\s*올라카나|비\s*오겠나", "비 와"),
    (r"덥노|덥나|덥데이", "더워"),
    (r"춥노|춥나|춥데이|춥다", "추워"),
    # 대답 (예 / 아니오)
    (r"^하모(요|예)?$|^하모\b", "그래"),
    (r"^(맞다|맞심더|맞습니더|그래예|예예|야)$", "그래"),
    (r"아이다|아입니더|아인데|아이라", "아니야"),
    (r"됐다\s*마|됐심더", "됐어"),
    # 말끝
    (r"주이소|주소(?=$|\s)", "주세요"),
    (r"심더|습니더", "습니다"),
    (r"니더(?=$|\s)", "니다"),
    (r"쪼매|쪼끔|쪼깨", "조금"),
    (r"억수로|디기|천지로", "아주"),
    (r"단디", "단단히"),
    (r"좋데이|좋네예|좋심더|좋다카이", "좋다"),
    (r"아푸다|아푸네|아파\s*죽겠다", "아프다"),
    (r"(아프|아파|어지럽|어지러|힘들)(노|나|데이|네예)(?=$|\s|\?)", r"\1"),
    (r"(\S)(노|나|고)\?$", r"\1?"),
]
_COMPILED = [(re.compile(p), r) for p, r in RULES]


def normalize(text: str) -> str:
    """사투리를 표준어로 바꾼 문장 (바꿀 게 없으면 그대로)"""
    out = (text or "").strip()
    for pat, rep in _COMPILED:
        out = pat.sub(rep, out)
    return re.sub(r"\s+", " ", out).strip()


if __name__ == "__main__":
    for s in ["약 뭐 묵노", "와 이리 어지럽노", "머라카노", "고마 됐다", "날 좀 살리도",
              "지금 몇 시고", "비 오나", "약 무따", "하모", "아이다 괜찮다", "고마워", "아이고 머리야",
              "아들한테 저녁 묵었다고 전해 도", "단디 챙기래이", "자빠졌다 도와도"]:
        print(f"{s:28s} → {normalize(s)}")
